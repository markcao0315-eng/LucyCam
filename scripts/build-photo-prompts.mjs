import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const source=new URL('../docs/LucyCam-照片分析Agent操作手册.md',import.meta.url);
const manual=(await readFile(source,'utf8')).replaceAll('\r\n','\n');
const blocks={};
for(const [key,marker] of [['core','CORE'],['compose','COMPOSE'],['guide','GUIDE']]){
  const begin=`<!-- RUNTIME_${marker}_BEGIN -->`,end=`<!-- RUNTIME_${marker}_END -->`;
  if(manual.split(begin).length!==2||manual.split(end).length!==2)throw new Error(`Missing or duplicate prompt marker: ${marker}`);
  blocks[key]=manual.split(begin)[1].split(end)[0].trim();
  if(!blocks[key])throw new Error(`Empty prompt: ${marker}`);
}
const hash=createHash('sha256').update(JSON.stringify(blocks)).digest('hex');
const generated=`// Generated from the photo-analysis manual, runtime blocks only.\n// Run npm run prompts:build after changing A/B; do not edit this file by hand.\nexport const promptVersion='photo-manual-1.4';\nexport const promptHash=${JSON.stringify(hash)};\nexport const photoRules=${JSON.stringify(blocks,null,2)};\nexport const photographyPrompt=guide=>photoRules.core+'\\n\\n'+(guide?photoRules.guide:photoRules.compose);\n`;
await writeFile(new URL('../photo-prompts.mjs',import.meta.url),generated);
console.log(`Generated A+B1 / A+B2; runtime hash ${hash}`);
